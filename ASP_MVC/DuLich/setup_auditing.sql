-- Bước 2.2: Tạo Procedure để truy vấn dữ liệu audit
CREATE OR REPLACE PROCEDURE TADMIN.GET_AUDIT_LOGS(
    p_table_name IN VARCHAR2,
    p_result OUT SYS_REFCURSOR
)
AS
    v_sql CLOB;
BEGIN
    v_sql := 'SELECT LogId, TableName, Action, ActionTimestamp, ActionBy, RecordId, OldValues, NewValues ' ||
             'FROM TADMIN.AUDIT_LOG_DETAIL ';

    IF p_table_name IS NOT NULL AND LENGTH(p_table_name) > 0 THEN
        IF UPPER(p_table_name) NOT IN ('HOADON', 'NHANVIEN', 'TOUR', 'DATTOUR') THEN
            RAISE_APPLICATION_ERROR(-20001, 'Invalid table name specified for auditing.');
        END IF;
        v_sql := v_sql || 'WHERE UPPER(TableName) = UPPER(:p_table_name) ';
    END IF;

    v_sql := v_sql || 'ORDER BY ActionTimestamp DESC';

    IF p_table_name IS NOT NULL AND LENGTH(p_table_name) > 0 THEN
        OPEN p_result FOR v_sql USING p_table_name;
    ELSE
        OPEN p_result FOR v_sql;
    END IF;
END;
/

