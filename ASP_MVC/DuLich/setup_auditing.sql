-- Trigger cho bảng HoaDon
CREATE OR REPLACE TRIGGER TADMIN.TRG_AUDIT_HOADON
AFTER INSERT OR UPDATE OR DELETE ON TADMIN.HoaDon
FOR EACH ROW
DECLARE
    v_action NVARCHAR2(20);
    v_record_id NVARCHAR2(100);
    v_old_values CLOB := '{}';
    v_new_values CLOB := '{}';
    v_user NVARCHAR2(100);
BEGIN
    v_action := CASE WHEN INSERTING THEN 'INSERT' WHEN UPDATING THEN 'UPDATE' WHEN DELETING THEN 'DELETE' END;
    v_user := NVL(SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'), SYS_CONTEXT('USERENV', 'SESSION_USER'));

    IF v_action = 'DELETE' THEN
        v_record_id := :OLD.MaHoaDon;
        v_old_values := JSON_OBJECT(
            'MAHOADON' VALUE :OLD.MAHOADON, 'MADATTOUR' VALUE :OLD.MADATTOUR, 'SOTIEN' VALUE :OLD.SOTIEN,
            'NGAYXUAT' VALUE TO_CHAR(:OLD.NGAYXUAT, 'YYYY-MM-DD HH24:MI:SS'), 'TRANGTHAI' VALUE :OLD.TRANGTHAI
        );
    ELSE
        v_record_id := :NEW.MaHoaDon;
    END IF;

    IF v_action = 'INSERT' THEN
        v_new_values := JSON_OBJECT(
            'MAHOADON' VALUE :NEW.MAHOADON, 'MADATTOUR' VALUE :NEW.MADATTOUR, 'SOTIEN' VALUE :NEW.SOTIEN,
            'NGAYXUAT' VALUE TO_CHAR(:NEW.NGAYXUAT, 'YYYY-MM-DD HH24:MI:SS'), 'TRANGTHAI' VALUE :NEW.TRANGTHAI
        );
    ELSIF v_action = 'UPDATE' THEN
        DECLARE
            json_obj_old JSON_OBJECT_T := JSON_OBJECT_T();
            json_obj_new JSON_OBJECT_T := JSON_OBJECT_T();
        BEGIN
            IF DECODE(:OLD.MADATTOUR, :NEW.MADATTOUR, 0, 1) = 1 THEN json_obj_old.put('MADATTOUR', :OLD.MADATTOUR); json_obj_new.put('MADATTOUR', :NEW.MADATTOUR); END IF;
            IF DECODE(:OLD.SOTIEN, :NEW.SOTIEN, 0, 1) = 1 THEN json_obj_old.put('SOTIEN', :OLD.SOTIEN); json_obj_new.put('SOTIEN', :NEW.SOTIEN); END IF;
            IF DECODE(:OLD.NGAYXUAT, :NEW.NGAYXUAT, 0, 1) = 1 THEN json_obj_old.put('NGAYXUAT', TO_CHAR(:OLD.NGAYXUAT, 'YYYY-MM-DD HH24:MI:SS')); json_obj_new.put('NGAYXUAT', TO_CHAR(:NEW.NGAYXUAT, 'YYYY-MM-DD HH24:MI:SS')); END IF;
            IF DECODE(:OLD.TRANGTHAI, :NEW.TRANGTHAI, 0, 1) = 1 THEN json_obj_old.put('TRANGTHAI', :OLD.TRANGTHAI); json_obj_new.put('TRANGTHAI', :NEW.TRANGTHAI); END IF;
            v_old_values := json_obj_old.to_clob();
            v_new_values := json_obj_new.to_clob();
        END;
    END IF;

    IF v_action IN ('INSERT', 'DELETE') OR (v_action = 'UPDATE' AND v_old_values != '{}') THEN
        INSERT INTO TADMIN.AUDIT_LOG_DETAIL (TableName, Action, ActionBy, RecordId, OldValues, NewValues)
        VALUES ('HoaDon', v_action, v_user, v_record_id, v_old_values, v_new_values);
    END IF;
END;
/

