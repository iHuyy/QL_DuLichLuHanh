-- =================================================================================
-- PHẦN 2: CÀI ĐẶT FINE-GRAINED AUDITING (FGA)
-- =================================================================================
-- Mô tả: Bật audit chi tiết (FGA) để ghi lại cả câu lệnh SQL.
-- Kết quả cũng được ghi vào UNIFIED_AUDIT_TRAIL.
-- =================================================================================
BEGIN
  DBMS_FGA.ADD_POLICY(
    object_schema   => 'TADMIN',
    object_name     => 'HoaDon',
    policy_name     => 'FGA_HOADON_POLICY',
    statement_types => 'INSERT,UPDATE,DELETE'
    audit_column_opts => DBMS_FGA.ALL_COLUMNS,
    audit_trail       => DBMS_FGA.DB_EXTENDED
  );
END;
