-- Bước 3.1: Tạo bảng để lưu trữ log chi tiết
CREATE TABLE TADMIN.AUDIT_LOG_DETAIL (
    LogId NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TableName NVARCHAR2(100),
    Action NVARCHAR2(20),
    ActionTimestamp TIMESTAMP DEFAULT SYSTIMESTAMP,
    RecordId NVARCHAR2(100),
    OldValues CLOB,
    NewValues CLOB,
    CONSTRAINT chk_action_v4 CHECK (Action IN ('INSERT', 'UPDATE', 'DELETE'))
);
/

-- Bước 3.2: Tạo trigger cho bảng NhanVien
CREATE OR REPLACE TRIGGER TADMIN.TRG_AUDIT_NHANVIEN
AFTER INSERT OR UPDATE OR DELETE ON TADMIN.NhanVien
FOR EACH ROW
DECLARE
    v_action NVARCHAR2(20);
    v_record_id NVARCHAR2(100);
    v_old_values CLOB := '{}';
    v_new_values CLOB := '{}';
BEGIN
    v_action := CASE WHEN INSERTING THEN 'INSERT' WHEN UPDATING THEN 'UPDATE' WHEN DELETING THEN 'DELETE' END;

    IF v_action = 'DELETE' THEN
        v_record_id := :OLD.MaNhanVien;
    ELSE
        v_record_id := :NEW.MaNhanVien;
    END IF;

    IF v_action = 'INSERT' THEN
        v_new_values := JSON_OBJECT('MANHANVIEN' VALUE :NEW.MANHANVIEN, 'HOTEN' VALUE :NEW.HOTEN, 'EMAIL' VALUE :NEW.EMAIL, 'VAITRO' VALUE :NEW.VAITRO, 'TRANGTHAI' VALUE :NEW.TRANGTHAI, 'MACHINHANH' VALUE :NEW.MACHINHANH);
    ELSIF v_action = 'UPDATE' THEN
        DECLARE
            json_obj_old JSON_OBJECT_T := JSON_OBJECT_T();
            json_obj_new JSON_OBJECT_T := JSON_OBJECT_T();
        BEGIN
            IF (:OLD.HOTEN <> :NEW.HOTEN OR (:OLD.HOTEN IS NULL AND :NEW.HOTEN IS NOT NULL) OR (:OLD.HOTEN IS NOT NULL AND :NEW.HOTEN IS NULL)) THEN json_obj_old.put('HOTEN', :OLD.HOTEN); json_obj_new.put('HOTEN', :NEW.HOTEN); END IF;
            IF (:OLD.EMAIL <> :NEW.EMAIL OR (:OLD.EMAIL IS NULL AND :NEW.EMAIL IS NOT NULL) OR (:OLD.EMAIL IS NOT NULL AND :NEW.EMAIL IS NULL)) THEN json_obj_old.put('EMAIL', :OLD.EMAIL); json_obj_new.put('EMAIL', :NEW.EMAIL); END IF;
            IF (:OLD.SODIENTHOAI <> :NEW.SODIENTHOAI OR (:OLD.SODIENTHOAI IS NULL AND :NEW.SODIENTHOAI IS NOT NULL) OR (:OLD.SODIENTHOAI IS NOT NULL AND :NEW.SODIENTHOAI IS NULL)) THEN json_obj_old.put('SODIENTHOAI', :OLD.SODIENTHOAI); json_obj_new.put('SODIENTHOAI', :NEW.SODIENTHOAI); END IF;
            IF (:OLD.VAITRO <> :NEW.VAITRO OR (:OLD.VAITRO IS NULL AND :NEW.VAITRO IS NOT NULL) OR (:OLD.VAITRO IS NOT NULL AND :NEW.VAITRO IS NULL)) THEN json_obj_old.put('VAITRO', :OLD.VAITRO); json_obj_new.put('VAITRO', :NEW.VAITRO); END IF;
            IF (:OLD.TRANGTHAI <> :NEW.TRANGTHAI OR (:OLD.TRANGTHAI IS NULL AND :NEW.TRANGTHAI IS NOT NULL) OR (:OLD.TRANGTHAI IS NOT NULL AND :NEW.TRANGTHAI IS NULL)) THEN json_obj_old.put('TRANGTHAI', :OLD.TRANGTHAI); json_obj_new.put('TRANGTHAI', :NEW.TRANGTHAI); END IF;
            IF (:OLD.MACHINHANH <> :NEW.MACHINHANH OR (:OLD.MACHINHANH IS NULL AND :NEW.MACHINHANH IS NOT NULL) OR (:OLD.MACHINHANH IS NOT NULL AND :NEW.MACHINHANH IS NULL)) THEN json_obj_old.put('MACHINHANH', :OLD.MACHINHANH); json_obj_new.put('MACHINHANH', :NEW.MACHINHANH); END IF;
            v_old_values := json_obj_old.to_clob();
            v_new_values := json_obj_new.to_clob();
        END;
    END IF;

    IF v_action IN ('INSERT', 'DELETE') OR (v_action = 'UPDATE' AND v_old_values != '{}') THEN
        INSERT INTO TADMIN.AUDIT_LOG_DETAIL (TableName, Action, RecordId, OldValues, NewValues)
        VALUES ('NhanVien', v_action, v_record_id, v_old_values, v_new_values);
    END IF;
END;
/

