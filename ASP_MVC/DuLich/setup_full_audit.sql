-- =================================================================================
-- PHẦN 3: CÀI ĐẶT TRIGGER-BASED AUDITING
-- =================================================================================
-- Mô tả: Cung cấp thông tin chi tiết nhất về giá trị cũ và mới.
-- FIX: So sánh NULL chính xác. Bỏ cột người thực hiện.
