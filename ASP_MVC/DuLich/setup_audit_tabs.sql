-- Trigger audit cho Tour
CREATE OR REPLACE TRIGGER TADMIN.TRG_AUD_TOUR
AFTER INSERT OR UPDATE OR DELETE ON TADMIN.TOUR
FOR EACH ROW
DECLARE
    v_action NVARCHAR2(20);
    v_record_id NVARCHAR2(100);
    v_old CLOB := '{}';
    v_new CLOB := '{}';
    jo_old JSON_OBJECT_T := JSON_OBJECT_T();
    jo_new JSON_OBJECT_T := JSON_OBJECT_T();
BEGIN
    v_action := CASE WHEN INSERTING THEN 'INSERT' WHEN UPDATING THEN 'UPDATE' ELSE 'DELETE' END;
    v_record_id := CASE WHEN DELETING THEN TO_CHAR(:OLD.MATOUR) ELSE TO_CHAR(:NEW.MATOUR) END;

    IF INSERTING THEN
        SELECT TO_CLOB(JSON_OBJECT(
            'MATOUR' VALUE :NEW.MATOUR, 'TIEUDE' VALUE :NEW.TIEUDE,
            'GIANGUOILON' VALUE :NEW.GIANGUOILON, 'GIATREEM' VALUE :NEW.GIATREEM,
            'TRANGTHAI' VALUE :NEW.TRANGTHAI, 'SOLUONG' VALUE :NEW.SOLUONG,
            'MACHINHANH' VALUE :NEW.MACHINHANH
        )) INTO v_new FROM dual;
    ELSIF DELETING THEN
        SELECT TO_CLOB(JSON_OBJECT(
            'MATOUR' VALUE :OLD.MATOUR, 'TIEUDE' VALUE :OLD.TIEUDE,
            'GIANGUOILON' VALUE :OLD.GIANGUOILON, 'GIATREEM' VALUE :OLD.GIATREEM,
            'TRANGTHAI' VALUE :OLD.TRANGTHAI, 'SOLUONG' VALUE :OLD.SOLUONG,
            'MACHINHANH' VALUE :OLD.MACHINHANH
        )) INTO v_old FROM dual;
    ELSE
        IF (:OLD.TIEUDE <> :NEW.TIEUDE OR (:OLD.TIEUDE IS NULL AND :NEW.TIEUDE IS NOT NULL) OR (:OLD.TIEUDE IS NOT NULL AND :NEW.TIEUDE IS NULL)) THEN jo_old.put('TIEUDE', :OLD.TIEUDE); jo_new.put('TIEUDE', :NEW.TIEUDE); END IF;
        IF (:OLD.GIANGUOILON <> :NEW.GIANGUOILON OR (:OLD.GIANGUOILON IS NULL AND :NEW.GIANGUOILON IS NOT NULL) OR (:OLD.GIANGUOILON IS NOT NULL AND :NEW.GIANGUOILON IS NULL)) THEN jo_old.put('GIANGUOILON', :OLD.GIANGUOILON); jo_new.put('GIANGUOILON', :NEW.GIANGUOILON); END IF;
        IF (:OLD.GIATREEM <> :NEW.GIATREEM OR (:OLD.GIATREEM IS NULL AND :NEW.GIATREEM IS NOT NULL) OR (:OLD.GIATREEM IS NOT NULL AND :NEW.GIATREEM IS NULL)) THEN jo_old.put('GIATREEM', :OLD.GIATREEM); jo_new.put('GIATREEM', :NEW.GIATREEM); END IF;
        IF (:OLD.TRANGTHAI <> :NEW.TRANGTHAI OR (:OLD.TRANGTHAI IS NULL AND :NEW.TRANGTHAI IS NOT NULL) OR (:OLD.TRANGTHAI IS NOT NULL AND :NEW.TRANGTHAI IS NULL)) THEN jo_old.put('TRANGTHAI', :OLD.TRANGTHAI); jo_new.put('TRANGTHAI', :NEW.TRANGTHAI); END IF;
        IF (:OLD.SOLUONG <> :NEW.SOLUONG OR (:OLD.SOLUONG IS NULL AND :NEW.SOLUONG IS NOT NULL) OR (:OLD.SOLUONG IS NOT NULL AND :NEW.SOLUONG IS NULL)) THEN jo_old.put('SOLUONG', :OLD.SOLUONG); jo_new.put('SOLUONG', :NEW.SOLUONG); END IF;
        IF (:OLD.MACHINHANH <> :NEW.MACHINHANH OR (:OLD.MACHINHANH IS NULL AND :NEW.MACHINHANH IS NOT NULL) OR (:OLD.MACHINHANH IS NOT NULL AND :NEW.MACHINHANH IS NULL)) THEN jo_old.put('MACHINHANH', :OLD.MACHINHANH); jo_new.put('MACHINHANH', :NEW.MACHINHANH); END IF;

        IF jo_old.get_size = 0 THEN
            RETURN;
        END IF;

        v_old := jo_old.to_clob;
        v_new := jo_new.to_clob;
    END IF;

    INSERT INTO TADMIN.AUDIT_LOG_DETAIL (TableName, Action, RecordId, OldValues, NewValues)
    VALUES ('TOUR', v_action, v_record_id, v_old, v_new);
END;
/

