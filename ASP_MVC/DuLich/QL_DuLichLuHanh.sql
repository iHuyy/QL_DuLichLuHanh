CREATE PROFILE admin_profile LIMIT
    FAILED_LOGIN_ATTEMPTS 3             -- Sai mật khẩu 3 lần thì khóa
    PASSWORD_LOCK_TIME 0.0003472        -- Khóa 30s
    PASSWORD_LIFE_TIME 90               -- Mật khẩu hết hạn sau 90 ngày
    SESSIONS_PER_USER 3                 -- Tối đa 3 phiên đăng nhập đồng thời
    IDLE_TIME 30                        -- Tự ngắt nếu không hoạt động 30 phút
    CONNECT_TIME 240                    -- Giới hạn thời gian kết nối 4 tiếng
    CPU_PER_SESSION UNLIMITED
    CPU_PER_CALL UNLIMITED
    LOGICAL_READS_PER_SESSION UNLIMITED;

CREATE PROFILE cus_profile LIMIT
    FAILED_LOGIN_ATTEMPTS 3
    PASSWORD_LOCK_TIME 0.0003472        -- Khóa 30s
    PASSWORD_LIFE_TIME 180              -- Khách hàng đổi mật khẩu 6 tháng 1 lần
    SESSIONS_PER_USER 3                 -- Chỉ 1 phiên đăng nhập duy nhất
    IDLE_TIME 15                        -- Hết hoạt động 15 phút -> tự ngắt
    CONNECT_TIME 120;                    -- Giới hạn 2 tiếng mỗi lần đăng nhập

CREATE PROFILE staff_profile LIMIT
    FAILED_LOGIN_ATTEMPTS 3
    PASSWORD_LIFE_TIME 90
    SESSIONS_PER_USER 1
    IDLE_TIME 30
    PASSWORD_GRACE_TIME 7;

