                                                                      'Đang diễn ra',
                                                                      'Hoàn thành',
                                                                      'Tạm ngưng',
                                                                      'Đã kết thúc',
                                                                      'Đã hủy',
                                                                      'Ẩn' ) ),
   soluong     number,
   qr          clob,
   machinhanh  number,
   chinhanh    nvarchar2(100),
   constraint fk_tour_cn foreign key ( machinhanh )
      references chinhanh ( machinhanh )
);


create table anhtour (
