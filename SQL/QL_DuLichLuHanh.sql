create table hoadon (
   mahoadon  number generated by default as identity primary key,
   madattour number,
   sotien    number(12,2),
   ngayxuat  date default sysdate,
   trangthai nvarchar2(30) default N'Chưa thanh toán' check ( lower(trangthai) in ( 'chưa thanh toán',
                                                                                    'đã thanh toán',
                                                                                    'hoàn tất' ) ),
   chukyso   nvarchar2(500),
